'use client';

import { useActionState } from 'react';
import { SubmitButton } from '@/components/submit-button';
import { TextField } from '@/components/ui/fields';
import { Alert } from '@/components/ui/surface';
import { initialActionState } from '@/lib/action-state';
import { startEnrollmentAction, verifyMfaAction, type EnrollState } from './actions';

export function VerifyForm({ factorId, next, label = 'Verify' }: { factorId: string; next: string; label?: string }) {
  const [state, action] = useActionState(verifyMfaAction, initialActionState);
  return (
    <form action={action} className="space-y-4" noValidate>
      <input type="hidden" name="factorId" value={factorId} />
      <input type="hidden" name="next" value={next} />
      <TextField
        name="code" label="Authentication code" inputMode="numeric" autoComplete="one-time-code"
        maxLength={6} required autoFocus error={state.fieldErrors?.code}
      />
      <SubmitButton pendingLabel="Verifying…">{label}</SubmitButton>
    </form>
  );
}

export function EnrollPanel({ next }: { next: string }) {
  const [enrollment, start] = useActionState<EnrollState, FormData>(startEnrollmentAction, { ok: false });

  if (!enrollment.factorId) {
    return (
      <form action={start} className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm text-muted">
          <li>Install an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password…).</li>
          <li>Scan the QR code shown on the next screen.</li>
          <li>Enter the 6-digit code the app displays.</li>
        </ol>
        {enrollment.message && <Alert tone="danger" title={enrollment.message} />}
        <SubmitButton pendingLabel="Preparing…">Set up authenticator app</SubmitButton>
      </form>
    );
  }

  return (
    <div className="space-y-4">
      {/* A data-URI SVG generated by Supabase; next/image adds nothing here. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="QR code that adds PeopleCore to your authenticator app" width={176} height={176} className="mx-auto rounded-md bg-white p-2" />
      <div>
        <p className="text-xs text-muted">Can’t scan it? Enter this key in your app instead:</p>
        <code data-testid="totp-secret" className="mt-1 block break-all rounded-md bg-subtle px-2 py-1 text-sm text-fg">
          {enrollment.secret}
        </code>
      </div>
      <VerifyForm factorId={enrollment.factorId} next={next} label="Turn on two-step verification" />
    </div>
  );
}
