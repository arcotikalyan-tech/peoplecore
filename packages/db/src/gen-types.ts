import type { PGlite } from '@electric-sql/pglite';

/**
 * Emits a `Database` type in the same shape as `supabase gen types typescript`, introspected from a
 * migrated database. Used while no hosted Supabase project exists (ADR-005); once one does, the
 * official generator can replace this and the drift test keeps both honest.
 */

interface ColumnRow {
  table_name: string;
  column_name: string;
  typname: string;
  typtype: string;
  elem_typname: string | null;
  elem_typtype: string | null;
  nullable: boolean;
  has_default: boolean;
  identity: string;
  generated: string;
}

interface FunctionRow {
  proname: string;
  arg_names: string[] | null;
  arg_modes: string[] | null;
  arg_typnames: string[];
  arg_typtypes: string[];
  arg_elem_typnames: string[];
  arg_elem_typtypes: string[];
  nargs: number;
  ndefaults: number;
  ret_typname: string;
  ret_typtype: string;
  retset: boolean;
}

const STRING_TYPES = new Set(['uuid', 'text', 'varchar', 'bpchar', 'char', 'date', 'timestamptz', 'timestamp', 'time', 'timetz', 'interval', 'inet', 'citext', 'daterange', 'tstzrange']);
const NUMBER_TYPES = new Set(['int2', 'int4', 'int8', 'float4', 'float8', 'numeric']);

function tsType(typname: string, typtype: string, elem?: { typname: string | null; typtype: string | null }): string {
  if (typname.startsWith('_') && elem?.typname) return `${tsType(elem.typname, elem.typtype ?? 'b')}[]`;
  if (typtype === 'e') return `Database['public']['Enums']['${typname}']`;
  if (STRING_TYPES.has(typname)) return 'string';
  if (NUMBER_TYPES.has(typname)) return 'number';
  if (typname === 'bool') return 'boolean';
  if (typname === 'json' || typname === 'jsonb') return 'Json';
  if (typname === 'void') return 'undefined';
  return 'unknown';
}

export async function generateDatabaseTypes(db: PGlite): Promise<string> {
  const columns = (
    await db.query<ColumnRow>(`
      select c.relname as table_name, a.attname as column_name, t.typname, t.typtype,
             et.typname as elem_typname, et.typtype as elem_typtype,
             not a.attnotnull as nullable, a.atthasdef as has_default,
             a.attidentity::text as identity, a.attgenerated::text as generated
        from pg_class c
        join pg_namespace n on n.oid = c.relnamespace
        join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
        join pg_type t on t.oid = a.atttypid
        left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
       where n.nspname = 'public' and c.relkind in ('r', 'p')
       order by c.relname, a.attnum`)
  ).rows;

  const enums = (
    await db.query<{ typname: string; labels: string[] }>(`
      select t.typname, array_agg(e.enumlabel order by e.enumsortorder) as labels
        from pg_type t
        join pg_enum e on e.enumtypid = t.oid
        join pg_namespace n on n.oid = t.typnamespace
       where n.nspname = 'public'
       group by t.typname
       order by t.typname`)
  ).rows;

  const functions = (
    await db.query<FunctionRow>(`
      with args as (
        select p.oid as proc, a.n, t.typname::text as typname, t.typtype::text as typtype,
               coalesce(et.typname::text, '') as elem_typname, coalesce(et.typtype::text, '') as elem_typtype
          from pg_proc p
          cross join lateral unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, n)
          join pg_type t on t.oid = a.oid
          left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
      )
      select p.proname, p.proargnames as arg_names, p.proargmodes::text[] as arg_modes,
             array(select typname from args where proc = p.oid order by n) as arg_typnames,
             array(select typtype from args where proc = p.oid order by n) as arg_typtypes,
             array(select elem_typname from args where proc = p.oid order by n) as arg_elem_typnames,
             array(select elem_typtype from args where proc = p.oid order by n) as arg_elem_typtypes,
             p.pronargs as nargs, p.pronargdefaults as ndefaults,
             rt.typname as ret_typname, rt.typtype::text as ret_typtype, p.proretset as retset
        from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
        join pg_type rt on rt.oid = p.prorettype
       where n.nspname = 'public' and p.prokind = 'f'
       order by p.proname`)
  ).rows;

  const out: string[] = [
    '// GENERATED by packages/db/src/gen-types.ts from supabase/migrations. Do not edit by hand.',
    '// Regenerate: corepack pnpm --filter @peoplecore/db gen:types',
    '',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    '',
    'export type Database = {',
    '  public: {',
    '    Tables: {',
  ];

  const tables = [...new Set(columns.map((c) => c.table_name))];
  for (const table of tables) {
    const cols = columns.filter((c) => c.table_name === table);
    const field = (c: ColumnRow) => tsType(c.typname, c.typtype, { typname: c.elem_typname, typtype: c.elem_typtype });
    out.push(`      ${table}: {`);
    out.push('        Row: {');
    for (const c of cols) out.push(`          ${c.column_name}: ${field(c)}${c.nullable ? ' | null' : ''};`);
    out.push('        };');
    out.push('        Insert: {');
    for (const c of cols) {
      if (c.generated !== '' || c.identity === 'a') out.push(`          ${c.column_name}?: never;`);
      else {
        const optional = c.nullable || c.has_default || c.identity !== '';
        out.push(`          ${c.column_name}${optional ? '?' : ''}: ${field(c)}${c.nullable ? ' | null' : ''};`);
      }
    }
    out.push('        };');
    out.push('        Update: {');
    for (const c of cols) {
      if (c.generated !== '' || c.identity === 'a') out.push(`          ${c.column_name}?: never;`);
      else out.push(`          ${c.column_name}?: ${field(c)}${c.nullable ? ' | null' : ''};`);
    }
    out.push('        };');
    out.push('        Relationships: [];');
    out.push('      };');
  }
  out.push('    };');
  out.push('    Views: { [_ in never]: never };');
  out.push('    Functions: {');
  for (const f of functions) {
    const names = f.arg_names ?? [];
    const modes = f.arg_modes ?? f.arg_typnames.map(() => 'i');
    const inputs: string[] = [];
    const outputs: string[] = [];
    let inputIndex = 0;
    const firstDefault = f.nargs - f.ndefaults;
    f.arg_typnames.forEach((typname, i) => {
      const name = names[i] ?? `arg${i}`;
      const ts = tsType(typname, f.arg_typtypes[i] ?? 'b', {
        typname: f.arg_elem_typnames[i] || null,
        typtype: f.arg_elem_typtypes[i] || null,
      });
      if (modes[i] === 'i' || modes[i] === 'b') {
        inputs.push(`          ${name}${inputIndex >= firstDefault ? '?' : ''}: ${ts};`);
        inputIndex += 1;
      }
      if (modes[i] === 't' || modes[i] === 'o' || modes[i] === 'b') outputs.push(`${name}: ${ts}`);
    });
    out.push(`      ${f.proname}: {`);
    out.push(inputs.length ? `        Args: {\n${inputs.join('\n')}\n        };` : '        Args: never;');
    const returns = outputs.length
      ? `{ ${outputs.join('; ')} }${f.retset ? '[]' : ''}`
      : `${tsType(f.ret_typname, f.ret_typtype)}${f.retset ? '[]' : ''}`;
    out.push(`        Returns: ${returns};`);
    out.push('      };');
  }
  out.push('    };');
  out.push('    Enums: {');
  for (const e of enums) out.push(`      ${e.typname}: ${e.labels.map((l) => `'${l}'`).join(' | ')};`);
  out.push('    };');
  out.push('    CompositeTypes: { [_ in never]: never };');
  out.push('  };');
  out.push('};');
  out.push('');
  out.push("type PublicSchema = Database['public'];");
  out.push("export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row'];");
  out.push("export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert'];");
  out.push("export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update'];");
  out.push("export type Enums<T extends keyof PublicSchema['Enums']> = PublicSchema['Enums'][T];");
  out.push('');
  return out.join('\n');
}
