// Prints SQL that seeds the permission catalog and role templates from @peoplecore/shared.
// Use it to author a NEW migration when the catalog changes; never edit an applied migration.
import { PERMISSIONS, ROLE_KEYS, ROLE_TEMPLATES } from '../packages/shared/src/permissions.ts';

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const lines: string[] = ['-- Generated by scripts/gen-rbac-seed.ts from packages/shared/src/permissions.ts', ''];

lines.push('insert into public.permissions (key, module, description, is_sensitive) values');
lines.push(
  Object.entries(PERMISSIONS)
    .map(([k, d]) => `  (${q(k)}, ${q(d.module)}, ${q(d.description)}, ${'sensitive' in d && d.sensitive ? 'true' : 'false'})`)
    .join(',\n') + '\non conflict (key) do update set module = excluded.module, description = excluded.description, is_sensitive = excluded.is_sensitive;',
);
lines.push('', 'insert into app.role_templates (role_key, name, description) values');
lines.push(ROLE_KEYS.map((r) => `  (${q(r)}, ${q(ROLE_TEMPLATES[r].name)}, ${q(ROLE_TEMPLATES[r].description)})`).join(',\n') + ';');
lines.push('', 'insert into app.role_template_permissions (role_key, permission_key, scope) values');
lines.push(
  ROLE_KEYS.flatMap((r) => Object.entries(ROLE_TEMPLATES[r].grants).map(([p, s]) => `  (${q(r)}, ${q(p)}, ${q(s)})`)).join(',\n') + ';',
);
// eslint-disable-next-line no-console -- CLI output
console.log(lines.join('\n'));
