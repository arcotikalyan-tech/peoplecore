import { describe, expect, it } from 'vitest';
import { payslipDate, payslipLayout, payslipMoney, payslipStamp, type PayslipData } from '../src/payslip.ts';

const data = (o: Partial<PayslipData> = {}): PayslipData => ({
  organization: 'Example Labs', company: { legalName: 'Example Labs Private Limited', addressLines: ['4th Floor, Example Building,', 'Bengaluru, Karnataka - 560102'] },
  periodMonth: '2026-09-01',
  employee: { name: 'Test Person', code: 'EX-0004', designation: 'CEO', location: 'Bengaluru', dateOfBirth: '1997-09-23', joiningDate: '2025-06-27', uan: '100000000001', pan: 'ABCDE1234F' },
  regime: 'new', standardDays: 30, payableDays: 29.5, lopDays: 0.5, payment: { mode: 'BANK TRANSFER', accountNumber: '00001111222233' },
  earnings: [{ name: 'Basic Salary', amount: 40000 }], deductions: [{ name: 'Provident Fund', amount: 1800 }, { name: 'Income Tax', amount: 0 }],
  totals: { gross: 102000, deductions: 2000, net: 100000 },
  ...o,
});

describe('payslipLayout: one format for every organization', () => {
  it('puts every field where the owner’s payslip has it', () => {
    const L = payslipLayout(data());
    expect(L.company).toBe('EXAMPLE LABS PRIVATE LIMITED');
    expect(L.title).toBe('Payslip  for the month of  SEPTEMBER 2026');
    expect(L.left.map(([l]) => l)).toEqual(['Employee ID', 'Date of Birth', 'Designation', 'UAN Number', 'PF Number', 'Regime Type']);
    expect(L.right.map(([l]) => l)).toEqual(['Employee Name', 'Joining Date', 'Location', 'Pan Number', 'LOS']);
    expect(L.left[1]).toEqual(['Date of Birth', '23-SEP-1997']);
    expect(L.left[5]).toEqual(['Regime Type', 'New Regime']);
    expect(L.right[1]).toEqual(['Joining Date', '27-JUN-2025']);
    expect(L.days).toEqual([['STANDARD DAYS', '30'], ['DAYS WORKED', '29.5']]);
    expect(L.payment).toEqual([['PAYMENT', 'BANK TRANSFER'], ['A/C No.', '00001111222233']]);
    expect(L.deductions).toEqual([['Provident Fund', '1,800.00'], ['Income Tax', '0.00']]);
    expect(L.totals).toEqual({ earnings: '102,000.00', deductions: '2,000.00', net: '100,000.00' });
    expect(L.notes[1]).toContain('generated by the Example Labs Private Limited payroll.');
  });

  it('names a company stored in capitals in title case in the disclaimer, and falls back to the organization name', () => {
    expect(payslipLayout(data({ company: { legalName: 'DRONE CO PRIVATE LIMITED' } })).notes[1]).toContain('by the Drone Co Private Limited payroll');
    expect(payslipLayout(data({ company: undefined })).company).toBe('EXAMPLE LABS');
  });

  it('leaves what it doesn’t have blank and adds the time only when given', () => {
    const L = payslipLayout(data({ employee: { name: 'A', code: 'B' }, regime: null, standardDays: null, payment: undefined }));
    expect(L.left.slice(1).every(([, v]) => v === '')).toBe(true);
    expect(L.payment).toEqual([['PAYMENT', ''], ['A/C No.', '']]);
    expect(L.foot).toHaveLength(3);
    const timed = payslipLayout(data({ generatedAt: '2026-10-29T10:57:41Z', timeZone: 'Asia/Kolkata' })).foot;
    expect(timed.find((f) => f.italic)?.text).toBe('Thu Oct 29 16:27:41 IST 2026');
    expect(timed.at(-1)?.text).toBe('29/10/2026');
  });

  it('formats money, dates and times', () => {
    expect(payslipMoney(1234567.5)).toBe('1,234,567.50');
    expect(payslipMoney(1234567, false)).toBe('1,234,567');
    expect(payslipDate('2026-01-05')).toBe('05-JAN-2026');
    expect(payslipDate('')).toBe('');
    expect(payslipStamp(new Date('2026-01-01T00:00:00Z'), 'UTC').long).toBe('Thu Jan 01 00:00:00 UTC 2026');
  });
});
